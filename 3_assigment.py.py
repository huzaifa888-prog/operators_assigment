## A taxi charges Rs. 300 as a base fare and Rs. 50 per kilometer. You travel 8 km.

    # Create variables and calculate the total fare.

bare_fare = 300
charges_per_km = 50
travel = 8

total_charges = charges_per_km * travel
bare_fare_charges = total_charges + bare_fare

print("Total_fare: ", bare_fare_charges) 